package com.mcms.domain.enumeration;

/**
 * Material classification for inventory management.
 */
public enum MaterialCategory {
    /**
     * Mushroom spawn / grain spawn / liquid culture
     */
    SPAWN,
    /**
     * Bulk substrate material (straw, sawdust, etc.)
     */
    SUBSTRATE,
    /**
     * Nutritional supplements (gypsum, bran, lime)
     */
    SUPPLEMENT,
    /**
     * Chemicals (hydrogen peroxide, alcohol, etc.)
     */
    CHEMICAL,
    /**
     * Bags, boxes, labels, clamshells
     */
    PACKAGING,
    /**
     * Consumable equipment (filters, gloves, etc.)
     */
    EQUIPMENT_SUPPLY,
    /**
     * Miscellaneous
     */
    OTHER,
}
