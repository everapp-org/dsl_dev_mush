package com.mcms.domain.enumeration;

/**
 * Standard units of measure across supply chain.
 */
public enum UnitOfMeasure {
    /**
     * Kilograms
     */
    KG,
    /**
     * Grams
     */
    GRAM,
    /**
     * Liters
     */
    LITER,
    /**
     * Individual pieces / items
     */
    PIECE,
    /**
     * Bags (substrate, spawn)
     */
    BAG,
    /**
     * Boxes (packaging)
     */
    BOX,
    /**
     * Pallets
     */
    PALLET,
}
