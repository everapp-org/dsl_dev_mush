package com.mcms.domain.enumeration;

/**
 * Harvest quality grading.
 */
public enum QualityGrade {
    /**
     * Premium - perfect form, no defects
     */
    A_PREMIUM,
    /**
     * Standard - minor cosmetic imperfections
     */
    B_STANDARD,
    /**
     * Industrial - processing/drying only
     */
    C_INDUSTRIAL,
    /**
     * Waste - compost or discard
     */
    WASTE,
}
