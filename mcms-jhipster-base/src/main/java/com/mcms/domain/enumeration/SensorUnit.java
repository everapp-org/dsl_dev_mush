package com.mcms.domain.enumeration;

/**
 * Units of measurement for sensor readings.
 */
public enum SensorUnit {
    /**
     * Temperature in °C
     */
    CELSIUS,
    /**
     * Relative humidity %
     */
    HUMIDITY_PERCENT,
    /**
     * CO₂ concentration in ppm
     */
    PPM_CO2,
    /**
     * Light intensity in lux
     */
    LUX,
    /**
     * Air flow in m/s
     */
    AIRFLOW_MS,
}
